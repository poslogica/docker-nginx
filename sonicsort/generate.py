#!/usr/bin/env python3
"""
Regenerate <variant>/Dockerfile.sonicsort from upstream's generated
<variant>/Dockerfile (default variant: mainline/alpine-slim).

    python sonicsort/generate.py [mainline/alpine-slim]

Re-run after pulling an upstream nginx/docker-nginx update (e.g. a new
NGINX_VERSION) so SonicSort's build follows it.

The one change from upstream: the hardcoded `FROM alpine:<tag>` becomes
`FROM ${ALPINE_BASE}`, defaulting to that same public image. SonicSort passes
ALPINE_BASE=sonicsort-alpine:local -- its own Alpine, assembled from Alpine's
signed packages by poslogica/docker-alpine -- so nginx installs onto a base we
built. Everything else (NGINX_VERSION, nginx.org's signed packages, the
entrypoint scripts) is upstream's.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

HEADER = """\
#
# GENERATED by sonicsort/generate.py from ./Dockerfile -- do not edit;
# change the generator and re-run it instead.
#
# SonicSort build: upstream's Dockerfile with the Alpine base made overridable
# (ALPINE_BASE), so it builds on sonicsort-alpine:local from poslogica/docker-alpine.
#
"""


def generate(variant: str) -> Path:
    """Write <variant>/Dockerfile.sonicsort; returns its path."""
    src = ROOT / variant / "Dockerfile"
    text = src.read_text(encoding="utf-8")

    match = re.search(r"^FROM (alpine:\S+)$", text, re.M)
    if not match:
        sys.exit(f"{src}: no 'FROM alpine:...' line -- only alpine variants are supported")
    public_base = match.group(1)

    # Upstream's "generated, do not edit" banner, replaced by ours.
    text = re.sub(r"\A(#.*\n)+", "", text)
    text = text.replace(
        f"FROM {public_base}\n",
        f"ARG ALPINE_BASE={public_base}\nFROM ${{ALPINE_BASE}}\n",
        1,
    )

    out = src.with_name("Dockerfile.sonicsort")
    out.write_text(HEADER + text, encoding="utf-8", newline="\n")
    return out


if __name__ == "__main__":
    print(generate(sys.argv[1] if len(sys.argv) > 1 else "mainline/alpine-slim"))
